"""WhatsApp via Meta's Cloud API directly (no AWS End User Messaging Social).

API Gateway routes ``GET`` and ``POST /whatsapp/webhook`` here:
- GET answers Meta's subscription handshake (``hub.verify_token`` must match the stored secret).
- POST carries messages. The body is accepted only with a valid ``X-Hub-Signature-256``
  (HMAC-SHA256 of the raw body with the Meta app secret), then each message goes through the same
  ``WhatsAppIngest`` as the EUMS path. Replies, media downloads and QR image uploads use the Graph API.

Secrets (Secrets Manager, ``WA_SECRET_ARN``): ``verify_token`` (generated by the stack),
``access_token`` and ``app_secret`` (pasted in by a person from the Meta app dashboard).
Privacy (P6): numbers and message text are never logged.
"""
from __future__ import annotations

import base64
import hashlib
import hmac as _hmac
import json
import os
import time
import urllib.error
import urllib.request
import uuid
from typing import Any, Callable

from .whatsapp import WhatsAppIngest, parse_webhook

GRAPH = "https://graph.facebook.com"
GRAPH_VERSION = os.environ.get("WA_GRAPH_VERSION", "v23.0")


def valid_signature(raw: bytes, header: str | None, app_secret: str) -> bool:
    if not header or not header.startswith("sha256=") or not app_secret:
        return False
    want = _hmac.new(app_secret.encode(), raw, hashlib.sha256).hexdigest()
    return _hmac.compare_digest(want, header[7:])


class GraphClient:
    """Minimal WhatsApp Cloud API client. ``opener`` is injectable for tests."""

    def __init__(self, token: str, phone_number_id: str, version: str = GRAPH_VERSION,
                 opener: Callable[[urllib.request.Request], Any] | None = None):
        self.token, self.pnid, self.version = token, phone_number_id, version
        self.open = opener or (lambda req: urllib.request.urlopen(req, timeout=10))

    def _req(self, url: str, data: bytes | None = None, ctype: str | None = None, method: str | None = None) -> bytes:
        req = urllib.request.Request(url, data=data, method=method or ("POST" if data is not None else "GET"))
        req.add_header("Authorization", f"Bearer {self.token}")
        if ctype:
            req.add_header("Content-Type", ctype)
        try:
            with self.open(req) as r:
                return r.read()
        except urllib.error.HTTPError as e:   # surface Meta's error code, never the token
            detail = e.read()[:300].decode("utf-8", "replace")
            raise RuntimeError(f"Graph API {e.code}: {detail}") from None

    def send(self, payload: dict) -> dict:
        return json.loads(self._req(f"{GRAPH}/{self.version}/{self.pnid}/messages", json.dumps(payload).encode(), "application/json"))

    def upload_png(self, png: bytes) -> str:
        boundary = uuid.uuid4().hex
        parts = [
            f'--{boundary}\r\nContent-Disposition: form-data; name="messaging_product"\r\n\r\nwhatsapp\r\n'.encode(),
            f'--{boundary}\r\nContent-Disposition: form-data; name="type"\r\n\r\nimage/png\r\n'.encode(),
            (f'--{boundary}\r\nContent-Disposition: form-data; name="file"; filename="qr.png"\r\n'
             'Content-Type: image/png\r\n\r\n').encode() + png + b"\r\n",
            f"--{boundary}--\r\n".encode(),
        ]
        r = json.loads(self._req(f"{GRAPH}/{self.version}/{self.pnid}/media", b"".join(parts), f"multipart/form-data; boundary={boundary}"))
        return r["id"]

    def download(self, media_id: str) -> tuple[bytes, str | None]:
        meta = json.loads(self._req(f"{GRAPH}/{self.version}/{media_id}"))
        return self._req(meta["url"]), meta.get("mime_type")


# ---------------------------------------------------------------- Lambda wiring (AWS only below)
_cache: dict[str, Any] = {"at": 0.0, "secret": None, "ingest": None}


def _secret() -> dict:
    if _cache["secret"] is None or time.time() - _cache["at"] > 300:   # pick up a pasted token within 5 minutes
        import boto3  # noqa: PLC0415
        sm = boto3.client("secretsmanager")
        _cache["secret"] = json.loads(sm.get_secret_value(SecretId=os.environ["WA_SECRET_ARN"])["SecretString"])
        _cache["at"], _cache["ingest"] = time.time(), None
    return _cache["secret"]


def ingest() -> WhatsAppIngest:
    sec = _secret()
    if _cache["ingest"] is None:
        import boto3  # noqa: PLC0415

        from capture.handlers.wiring import REGION, extractor, service, transcriber  # noqa: PLC0415
        from ledger.aws import KmsPhoneHasher  # noqa: PLC0415

        svc = service()
        g = GraphClient(sec["access_token"], os.environ["WA_PHONE_NUMBER_ID"])
        s3 = boto3.client("s3", region_name=REGION)
        kms = boto3.client("kms", region_name=REGION)
        data_key = os.environ["DATA_KEY_ARN"]

        def fetch(media_id, _origin, key):
            body, mime = g.download(media_id)
            s3.put_object(Bucket=svc.settings.evidence_bucket, Key=key, Body=body, ContentType=mime or "application/octet-stream")

        def upload_image(_origin, png):
            return g.upload_png(png)

        _cache["ingest"] = WhatsAppIngest(
            svc, hmac=KmsPhoneHasher(os.environ["PHONE_HMAC_KEY_ARN"], REGION), send=lambda _origin, p: g.send(p),
            fetch_media=fetch,
            encrypt=lambda s: base64.b64encode(kms.encrypt(KeyId=data_key, Plaintext=s.encode(),
                                                           EncryptionContext={"use": "wa-reply"})["CiphertextBlob"]).decode(),
            decrypt=lambda s: kms.decrypt(CiphertextBlob=base64.b64decode(s),
                                          EncryptionContext={"use": "wa-reply"})["Plaintext"].decode(),
            extractor=extractor(), transcriber=transcriber(), upload_image=upload_image)
    return _cache["ingest"]


def _resp(status: int, body: str = "", ctype: str = "text/plain") -> dict:
    return {"statusCode": status, "headers": {"content-type": ctype}, "body": body}


def route(event: dict, secret: Callable[[], dict], on_message: Callable[[Any], str], log=None) -> dict:
    """Pure request routing, so it is testable without AWS."""
    method = (event.get("requestContext", {}).get("http", {}).get("method") or "").upper()
    if method == "GET":
        q = event.get("queryStringParameters") or {}
        if q.get("hub.mode") == "subscribe" and q.get("hub.verify_token") and _hmac.compare_digest(
                q["hub.verify_token"], secret().get("verify_token", "")):
            return _resp(200, q.get("hub.challenge", ""))
        return _resp(403, "forbidden")
    if method != "POST":
        return _resp(405, "method not allowed")
    raw = event.get("body") or ""
    raw_b = base64.b64decode(raw) if event.get("isBase64Encoded") else raw.encode()
    headers = {k.lower(): v for k, v in (event.get("headers") or {}).items()}
    if not valid_signature(raw_b, headers.get("x-hub-signature-256"), secret().get("app_secret", "")):
        return _resp(401, "bad signature")
    try:
        msgs = parse_webhook(json.loads(raw_b))
    except ValueError:
        return _resp(400, "bad json")
    results = []
    for m in msgs:
        try:
            results.append(on_message(m))
        except Exception:  # noqa: BLE001  one bad message must not make Meta retry the whole batch
            if log:
                log.exception("message failed", extra={"message_id": m.message_id, "kind": m.kind})
            results.append("error")
    if log:
        log.info("processed", extra={"results": results})   # never numbers or text
    return _resp(200, json.dumps({"results": results}), "application/json")


def handler(event, context):
    from aws_lambda_powertools import Logger  # noqa: PLC0415
    log = Logger(service="whatsapp-cloud")
    return route(event, _secret, lambda m: ingest().on_message(m), log)
